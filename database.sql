create or replace function public.respond_to_quote(quote_id bigint, decision text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  quote_state text;
  quote_expiration date;
begin
  if coalesce(public.current_app_role(), '') <> 'Cliente' then
    raise exception 'Solo el cliente puede responder a su cotización.';
  end if;
  if decision not in ('Aprobada', 'Rechazada') then
    raise exception 'La respuesta debe ser Aprobada o Rechazada.';
  end if;
  select estado, fecha_vencimiento into quote_state, quote_expiration
  from public.cotizaciones
  where id = quote_id and "clienteId" = public.current_cliente_id()
  for update;
  if not found then
    raise exception 'No se encontró una cotización asociada a esta cuenta.';
  end if;
  if quote_state not in ('Enviada', 'Vista') then
    raise exception 'La cotización no está disponible para respuesta.';
  end if;
  if quote_expiration is not null and quote_expiration < current_date then
    raise exception 'La cotización está vencida y ya no puede responderse.';
  end if;
  update public.cotizaciones
  set estado = decision, updated_at = now()
  where id = quote_id;
end;
$$;

revoke all on function public.respond_to_quote(bigint, text) from public, anon;
grant execute on function public.respond_to_quote(bigint, text) to authenticated;

create or replace function public.convert_quote_to_order(
  p_quote_id bigint,
  p_scheduled_date date,
  p_start_time time default null,
  p_technician_id bigint default null,
  p_service_address text default null,
  p_service_zone text default null,
  p_service_priority text default 'Normal'
)
returns public.ordenes
language plpgsql
security definer
set search_path = public
as $$
declare
  quote_record public.cotizaciones%rowtype;
  source_order public.ordenes%rowtype;
  new_order public.ordenes%rowtype;
  technician_record public.tecnicos%rowtype;
  new_order_id text;
begin
  if coalesce(public.current_app_role(), '') not in ('Administrador', 'Supervisor') then
    raise exception 'No tienes permiso para convertir cotizaciones en órdenes.';
  end if;
  if p_scheduled_date is null then
    raise exception 'Debes indicar la fecha programada.';
  end if;
  if p_scheduled_date < current_date then
    raise exception 'La fecha programada no puede ser anterior a hoy.';
  end if;
  if coalesce(p_service_priority, 'Normal') not in ('Baja', 'Normal', 'Alta', 'Urgente') then
    raise exception 'La prioridad seleccionada no es válida.';
  end if;

  select * into quote_record
  from public.cotizaciones
  where id = p_quote_id
  for update;
  if not found then
    raise exception 'No se encontró la cotización.';
  end if;

  if quote_record.estado = 'Convertida' then
    select * into new_order from public.ordenes where id = quote_record.orden_id;
    if found then return new_order; end if;
    raise exception 'La cotización figura convertida, pero no se encontró su orden.';
  end if;
  if quote_record.estado <> 'Aprobada' then
    raise exception 'Solo se pueden convertir cotizaciones aprobadas.';
  end if;

  select * into source_order from public.ordenes where id = quote_record.orden_id;
  if not found then
    raise exception 'La cotización no tiene una orden de origen válida.';
  end if;

  if p_technician_id is not null then
    select * into technician_record
    from public.tecnicos
    where id = p_technician_id and estado = 'Activo';
    if not found then
      raise exception 'El técnico seleccionado no está activo.';
    end if;
  end if;

  new_order_id := 'OT-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12));
  insert into public.ordenes (
    id, "vehiculoId", "clienteId", servicio, estado, fecha, tecnico, descripcion,
    direccion, hora_inicio, duracion_estimada, tecnico_id, zona, prioridad,
    observaciones, created_by
  ) values (
    new_order_id, quote_record."vehiculoId", quote_record."clienteId",
    source_order.servicio,
    case when technician_record.id is null then 'Pendiente' else 'Asignado' end,
    p_scheduled_date::text,
    technician_record.nombre,
    coalesce(nullif(quote_record.observaciones, ''), source_order.descripcion),
    coalesce(nullif(p_service_address, ''), source_order.direccion),
    p_start_time,
    source_order.duracion_estimada,
    technician_record.id,
    coalesce(nullif(p_service_zone, ''), source_order.zona),
    coalesce(nullif(p_service_priority, ''), source_order.prioridad, 'Normal'),
    'Orden generada desde cotización ' || quote_record.numero || '.',
    auth.uid()
  )
  returning * into new_order;

  update public.cotizaciones
  set estado = 'Convertida', orden_id = new_order.id, updated_at = now()
  where id = quote_record.id;

  insert into public.activity_logs (
    user_id, cliente_id, vehiculo_id, orden_id, entidad, entidad_id, accion, descripcion
  ) values (
    auth.uid(), new_order."clienteId", new_order."vehiculoId", new_order.id,
    'cotización', quote_record.numero, 'convertida',
    'La cotización ' || quote_record.numero || ' generó la orden ' || new_order.id || '.'
  );

  return new_order;
end;
$$;

