create or replace function public.enforce_technician_order_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.current_app_role() = 'Técnico' then
    if row(
      new.id, new."vehiculoId", new."clienteId", new.servicio, new.fecha,
      new.tecnico, new.descripcion, new.direccion, new.hora_inicio, new.duracion_estimada,
      new.tecnico_id, new.zona, new.prioridad, new.observaciones, new.created_by, new.created_at
    ) is distinct from row(
      old.id, old."vehiculoId", old."clienteId", old.servicio, old.fecha,
      old.tecnico, old.descripcion, old.direccion, old.hora_inicio, old.duracion_estimada,
      old.tecnico_id, old.zona, old.prioridad, old.observaciones, old.created_by, old.created_at
    ) then
      raise exception 'El técnico solo puede actualizar el estado de sus órdenes asignadas.';
    end if;
    if new.estado not in ('Asignado', 'Confirmado', 'En proceso', 'Esperando repuestos', 'Completado') then
      raise exception 'El estado no está permitido para un técnico.';
    end if;
  end if;
  return new;
end;
$$;

