create or replace function public.notify_order_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target_user uuid;
  message_text text;
begin
  if new.tecnico_id is not null and (
    tg_op = 'INSERT'
    or old.tecnico_id is distinct from new.tecnico_id
    or old.fecha is distinct from new.fecha
    or old.hora_inicio is distinct from new.hora_inicio
    or old.estado is distinct from new.estado
  ) then
    select user_id into target_user from public.tecnicos where id = new.tecnico_id;
    if target_user is not null then
      message_text := case
        when tg_op = 'INSERT' then 'Se te asignó la orden ' || new.id || ' para el ' || new.fecha || '.'
        else 'La orden ' || new.id || ' fue actualizada: ' || new.estado || ', ' || new.fecha || '.'
      end;
      insert into public.notificaciones (user_id, titulo, mensaje, tipo, enlace)
      values (target_user, 'Actualización de orden', message_text, 'orden', '/agenda');
    end if;
  end if;
  return new;
end;
$$;

