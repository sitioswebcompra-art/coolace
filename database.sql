-- Publica los cambios operativos para que las sesiones abiertas se actualicen en vivo.
do $$
declare
  table_name text;
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    raise notice 'No existe la publicacion supabase_realtime; habilita Realtime en el proyecto Supabase.';
    return;
  end if;

  foreach table_name in array array[
    'clientes', 'vehiculos', 'ordenes', 'tecnicos', 'informes_tecnicos',
    'cotizaciones', 'cotizacion_items', 'repuestos', 'notificaciones',
    'company_settings', 'profiles', 'activity_logs'
  ]
  loop
    if to_regclass(format('public.%I', table_name)) is not null
      and not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = table_name
      )
    then
      execute format('alter publication supabase_realtime add table public.%I', table_name);
    end if;
  end loop;
end;
$$;
