create or replace function public.admin_update_user_access(
  p_user_id uuid,
  p_role text,
  p_activo boolean,
  p_cliente_id bigint default null,
  p_tecnico_id bigint default null
)
returns public.profiles
language plpgsql
security definer
set search_path = public
as $$
declare
  target_profile public.profiles%rowtype;
  target_technician public.tecnicos%rowtype;
  updated_profile public.profiles%rowtype;
begin
  if public.current_app_role() is distinct from 'Administrador' then
    raise exception 'Solo un administrador puede asignar roles y permisos.';
  end if;
  perform pg_advisory_xact_lock(704202610);
  if p_role is null or p_role not in ('Administrador', 'Supervisor', 'Técnico', 'Área administrativa', 'Cliente') then
    raise exception 'El rol seleccionado no es válido.';
  end if;
  if p_activo is null then
    raise exception 'Debes indicar si la cuenta está activa.';
  end if;
  if p_role = 'Cliente' and p_activo and p_cliente_id is null then
    raise exception 'Asocia una cuenta de cliente para asignar el rol Cliente.';
  end if;
  if p_role = 'Técnico' and p_tecnico_id is null then
    raise exception 'Asocia un registro de técnico para asignar el rol Técnico.';
  end if;
  if p_role <> 'Cliente' and p_cliente_id is not null then
    raise exception 'Solo las cuentas de cliente pueden asociarse a un cliente.';
  end if;
  if p_role <> 'Técnico' and p_tecnico_id is not null then
    raise exception 'Solo las cuentas de técnico pueden asociarse a un técnico.';
  end if;

  select * into target_profile
  from public.profiles
  where id = p_user_id
  for update;
  if not found then
    raise exception 'No se encontró el perfil del usuario.';
  end if;
  if p_user_id = auth.uid()
    and (target_profile.role <> p_role or target_profile.activo is distinct from p_activo) then
    raise exception 'Usa otra cuenta administradora para cambiar tu propio rol o estado.';
  end if;

  if target_profile.role = 'Administrador' and target_profile.activo
    and (p_role <> 'Administrador' or not p_activo)
    and not exists (
      select 1 from public.profiles
      where id <> p_user_id and role = 'Administrador' and activo = true
    ) then
    raise exception 'No se puede desactivar o cambiar el rol del último administrador activo.';
  end if;

  if p_cliente_id is not null and not exists (
    select 1 from public.clientes where id::text = p_cliente_id::text
  ) then
    raise exception 'El cliente seleccionado no existe.';
  end if;

  if p_tecnico_id is not null then
    select * into target_technician
    from public.tecnicos
    where id = p_tecnico_id and estado = 'Activo'
    for update;
    if not found then
      raise exception 'El técnico seleccionado no existe o está inactivo.';
    end if;
    if target_technician.user_id is not null and target_technician.user_id <> p_user_id then
      raise exception 'Ese registro de técnico ya está asociado a otra cuenta.';
    end if;
  end if;

  update public.tecnicos
  set user_id = null, updated_at = now()
  where user_id = p_user_id
    and (p_role <> 'Técnico' or id <> p_tecnico_id);

  if p_tecnico_id is not null then
    update public.tecnicos
    set user_id = p_user_id, updated_at = now()
    where id = p_tecnico_id;
  end if;

  update public.profiles
  set role = p_role,
      activo = p_activo,
      cliente_id = p_cliente_id,
      updated_at = now()
  where id = p_user_id
  returning * into updated_profile;

  return updated_profile;
end;
$$;

revoke all on function public.admin_update_user_access(uuid, text, boolean, bigint, bigint) from public, anon;
grant execute on function public.admin_update_user_access(uuid, text, boolean, bigint, bigint) to authenticated;

